# -*- coding: utf-8 -*-
"""
手写数字识别 CNN 模型定义
============================================================
这是一个面向"学习机器学习"的演示，所以注释会讲清楚每一个部件
在"学什么 / 为什么这样设计"。边读边想，收获会很大。

数据：输入是 28x28 的灰度手写数字图（0~9），单通道。
输出：10 个分数，分别代表"模型认为这张图是数字 0/1/2/.../9"的把握。
     分数最大的那个数字就是模型的预测结果。

模型的整体思路（一句话）：用"卷积"不断抓取图片里的局部特征
（线条、拐角、圈），逐渐抽象，最后用"全连接层"做分类。

数据流概览（一个数字图片走完全程的样子）：
  28x28x1 输入
    -> Conv+BN+ReLU (32个卷积核) -> MaxPool     -> 14x14x32
    -> Conv+BN+ReLU (64个卷积核) -> MaxPool     ->  7x7x64
    -> 展平 (7*7*64 = 3136 个数)
    -> Linear(3136->128) -> ReLU -> Dropout
    -> Linear(128->10)                        -> 10 个分数
"""
import torch.nn as nn


class HandwritingCNN(nn.Module):
    """
    一个轻量但"麻雀虽小五脏俱全"的 CNN，专门用于讲解深度学习基础。
    参数约 42 万，纯 CPU 几十秒就能训完，非常适合学习与演示。
    """

    def __init__(self, dropout_p: float = 0.3, hidden: int = 128):
        """
        dropout_p:  Dropout 层随机"丢弃"神经元的比例（用于防止过拟合）。
        hidden:     全连接层的隐藏神经元数量（代表模型的"抽象能力"）。
        """
        super().__init__()

        # =================================================================
        # 第一部分：特征提取器（卷积 + 池化）
        # ----------------------------------------------------------------
        # 卷积层 Conv2d 是什么？
        #   想象拿一个小"放大镜/扫描窗口"（卷积核）在图片上滑动，
        #   每到一个位置就把窗口内的像素做个加权求和，得到一个数，
        #   把所有位置的结果排成一张"特征图"。窗口越到深处越能识别
        #   更高层的语义（浅层是边角线，深层是圆圈/笔画组合）。
        #   in_channels=1  -> 输入 1 个通道（灰度图）
        #   out_channels=32-> 用 32 个不同的卷积核，得到 32 张特征图
        #   kernel_size=3  -> 3x3 的扫描窗口
        #   padding=1      -> 图片四周补一圈 0，让输出尺寸和输入一致
        # BatchNorm2d 是什么？
        #   让每一批数据的数值分布保持"稳定、居中"，加速收敛、
        #   训练更稳。可以粗略理解为"给数据做归一化"。
        # ReLU 是什么？
        #   激活函数：负数直接变成 0（x>0 保留）。作用是把"线性计算"
        #   变成"能拟合任意复杂函数"的非线性变换（没有它，堆再多层
        #   也等价于一层）。
        # MaxPool2d(2) 是什么？
        #   下采样：在 2x2 小区域里只取最大值。作用一：压缩尺寸省计算；
        #   作用二：让特征对轻微平移更"鲁棒"（容忍小偏移）。
        # =================================================================
        self.features = nn.Sequential(
            nn.Conv2d(1, 32, kernel_size=3, padding=1),   # 28x28 -> 28x28
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(2),                              # 28x28 -> 14x14
            nn.Conv2d(32, 64, kernel_size=3, padding=1),  # 14x14
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(2),                              # 14x14 -> 7x7
        )

        # =================================================================
        # 第二部分：分类器（全连接层）
        # ----------------------------------------------------------------
        # 经过特征提取后，图片被压缩成 7x7x64 = 3136 个"高级特征"。
        # Flatten：把这 3136 个数拉直成一维向量（展平），交给全连接层。
        # Linear(3136->128)：全连接，每个输入都连到每个输出（权重巨大），
        #   相当于把前面提取到的特征"组合打分"。
        # Dropout(0.3)：训练时随机让 30% 的神经元输出置 0。为什么？
        #   防止网络"死记硬背"训练集（过拟合），逼它学通用规律，
        #   就像"不要只背答案，要理解原理"。
        # 最后的 Linear(128->10)：输出 10 个分数，一个类一个。
        # =================================================================
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64 * 7 * 7, hidden),
            nn.ReLU(inplace=True),
            nn.Dropout(p=dropout_p),
            nn.Linear(hidden, 10),
        )

    def forward(self, x):
        """
        前向传播：把输入 x 从"图片"一路变成"10 个分类分数"。
        这个被调用的方式很特殊：我们只写"数据怎么流"，不写怎么循环，
        框架（PyTorch）自动按定义好的网络结构把 x 传下去。
        """
        x = self.features(x)   # 提取特征：28x28 -> 7x7x64
        return self.classifier(x)  # 分类：变成 10 个分数

    def conv1_activations(self, x):
        """
        【学习辅助】只取"第一层卷积"的输出（还没池化之前），
        用来把神经网络"看到的东西"可视化给学习者看。
        features 的前 3 层 = Conv2d(32) -> BatchNorm -> ReLU，
        输出形状 (1, 32, 28, 28)，即 32 张特征图，每张 28x28。
        """
        return self.features[0:3](x)

    def summary(self):
        """打印模型参数量（学习时可直观感受网络规模）。"""
        n = sum(p.numel() for p in self.parameters())
        trainable = sum(p.numel() for p in self.parameters() if p.requires_grad)
        return f"HandwritingCNN 参数总量: {n:,} (可训练 {trainable:,})"
